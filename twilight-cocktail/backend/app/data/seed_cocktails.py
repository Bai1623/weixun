def ingredient(
    slug: str,
    name_zh: str,
    name_en: str,
    amount: str,
    order: int,
    requirement: str = "required",
) -> dict[str, Any]:
    return {
        "slug": slug,
        "name_zh": name_zh,
        "name_en": name_en,
        "amount": amount,
        "display_order": order,
        "requirement": requirement,
    }


def steps(name: str, method: str) -> list[dict[str, Any]]:
    return [
        {
            "step_number": 1,
            "instruction": "准备杯具、冰块和所有材料，按配方量好。",
            "technique": "准备",
            "tip": "先量材料再开始，能减少手忙脚乱。",
        },
        {
            "step_number": 2,
            "instruction": f"按配方完成{method}，让材料充分混合并降温。",
            "technique": method,
            "tip": None,
        },
        {
            "step_number": 3,
            "instruction": f"倒入杯中，完成{name}的装饰并立即品饮。",
            "technique": "出品",
            "tip": "冰饮类鸡尾酒最好在温度上升前饮用。",
        },
    ]


def cocktail(
    slug: str,
    name_zh: str,
    name_en: str,
    base_spirit: str,
    method: str,
    glass_type: str,
    difficulty: str,
    alcohol_level: str,
    flavors: dict[str, int],
    ingredients: list[dict[str, Any]],
    popularity: float,
    beginner: bool,
    is_iba: bool = True,
    is_alcoholic: bool = True,
    image_tone: str = "amber",
    image_url: str | None = None,
) -> dict[str, Any]:
    return {
        "slug": slug,
        "name_zh": name_zh,
        "name_en": name_en,
        "short_description": f"{name_zh}是一款适合在暮色时段练习的经典配方。",
        "story": f"{name_zh}用于帮助初学者理解{method}、风味平衡和杯型选择。",
        "image_url": image_url if image_url is not None else COCKTAIL_IMAGE_URLS.get(slug, ""),
        "image_tone": image_tone,
        "base_spirit": base_spirit,
        "glass_type": glass_type,
        "method": method,
        "difficulty": difficulty,
        "prep_minutes": 5 if difficulty == "easy" else 7,
        "alcohol_level": alcohol_level,
        "flavors": flavors,
        "tags": ["经典", "入门" if beginner else "进阶", base_spirit or "无酒精"],
        "popularity_weight": popularity,
        "beginner_friendly": beginner,
        "is_iba": is_iba,
        "is_alcoholic": is_alcoholic,
        "review_status": "approved",
        "source_name": "Local reviewed seed recipe / TheCocktailDB image",
        "ingredients": ingredients,
        "steps": steps(name_zh, method),
    }


